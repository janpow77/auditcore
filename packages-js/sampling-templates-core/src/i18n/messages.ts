/** Schlüssel aller Texte. */
export type MessageKey = keyof typeof de

/** Platzhalterwerte eines Texts. */
export type MessageParams = Readonly<Record<string, string | number>>

/** Übersetzungsfunktion, wie sie `useI18n` aus `@auditcore/ui` liefert. */
export type Translate = (key: MessageKey, params?: MessageParams) => string

/** Texte je Sprache; Deutsch vollständig, Englisch als Arbeitsübersetzung (`messages.en.ts`). */
export const samplingTemplatesMessages: { de: Readonly<Record<MessageKey, string>>; en: Readonly<Partial<Record<MessageKey, string>>> } = { de, en }

/** Kataloge mit überschriebenen Texten einer Anwendung. */
export function withMessages(
  overrides: { de?: Partial<Record<MessageKey, string>>; en?: Partial<Record<MessageKey, string>> } = {},
): typeof samplingTemplatesMessages {
  return { de: { ...samplingTemplatesMessages.de, ...overrides.de }, en: { ...samplingTemplatesMessages.en, ...overrides.en } }
}

/** Übersetzungsfunktion ohne Framework (Export, Tests): `{name}`-Platzhalter, Rückfall auf Deutsch. */
export function createTranslate(catalogs: typeof samplingTemplatesMessages = samplingTemplatesMessages, locale: 'de' | 'en' = 'de'): Translate {
  return (key, params) => {
    const template = (locale === 'en' ? catalogs.en[key] : undefined) ?? catalogs.de[key]
    return template.replace(/\{(\w+)\}/g, (match, name: string) => (params?.[name] === undefined ? match : String(params[name])))
  }
}
